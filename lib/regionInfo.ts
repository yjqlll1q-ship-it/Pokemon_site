/**
 * lib/regionInfo.ts
 * ---------------------------------------------------------------------------
 * 地区资料（**登记制**）：只有在这里登记过的地区才显示简介与原型说明。
 *
 * 为什么不做成全量必填：PokéAPI 的 region 端点只有多语言名称，没有简介文案；
 * 全量填写就等于我们要维护第二份「每代一段」的人工内容，而且每次加世代都会被
 * 拖着一起写。登记制下「没写简介」是正常状态（那一块不渲染），不是缺数据 ——
 * 与 TAGLINE_ZH（宣传飘带）同一个口径。
 *
 * 内容口径：只写**可核实的公开事实**（首次登场的作品、以日本哪一地地方为原型），
 * 不写主观评价。来源：Bulbapedia《Pokémon world》与各地区条目；作品中文名取官方简中。
 *
 * key = 世代编号（与 pokedex.json 的 generations[].id 一致）。
 */
export interface RegionInfo {
  /** 一句话简介（配合版面，控制在 ~50 字内） */
  blurb: string;
  /** 原型地（公开资料里的公开信息） */
  basedOn: string;
  /** 首次登场的作品（官方简中名） */
  debut: string;
}

